const HUMOR_LIST = AJAE_JOKES;

let _humorRevealed = false;
let _lastHumorIdx = -1;

function renderHumor(seed) {
  // 페이지 로드마다 다른 농담 (시간 기반 + 날짜 시드)
  const timeSeed = (seed + Date.now()) >>> 0;
  let s = timeSeed;
  const r = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 0xffffffff; };

  let idx;
  do {
    idx = Math.floor(r() * HUMOR_LIST.length);
  } while (idx === _lastHumorIdx && HUMOR_LIST.length > 1);
  _lastHumorIdx = idx;

  const joke = HUMOR_LIST[idx];
  _humorRevealed = false;

  const setup = joke[0], punchline = joke[1];
  const reaction = punchline.slice(-2); // 마지막 이모지

  document.getElementById('humor-setup').innerHTML =
    setup.replace(/\n/g, '<br>');
  document.getElementById('humor-punchline').textContent = punchline;
  document.getElementById('humor-punchline-wrap').style.display = 'none';
  document.getElementById('humor-reaction').style.display = 'none';
  document.getElementById('humor-reaction').textContent = '😂';

  const btn = document.getElementById('humor-btn');
  if (btn) {
    btn.style.display = 'inline-block';
    btn.textContent = '🤔 정답 보기';
  }
  // 한 번 더 보기 버튼 추가
  const moreBtn = document.getElementById('humor-more-btn');
  if (moreBtn) moreBtn.style.display = 'inline-block';
}

function revealPunchline() {
  document.getElementById('humor-punchline-wrap').style.display = 'block';
  const reaction = document.getElementById('humor-reaction');
  reaction.style.display = 'block';
  const btn = document.getElementById('humor-btn');
  if (btn) btn.style.display = 'none';
}

function nextHumor() {
  // 다른 농담 보기
  const seed = (Date.now() * Math.random()) >>> 0;
  renderHumor(seed);
}





